PER_CLASS = 400   # 목표 이름당 최대 장수(여러 242 이름이 한 이름에 모이면 합쳐서). 기존 AI Hub 74 가 이름당 약 200장이라 너무 넘치지 않게.


if __name__ == '__main__':
    import sys, collections
    names = [l.strip() for l in open(sys.argv[1], encoding='utf-8-sig') if l.strip()]           # 우리 이름(407)
    rows = [l.rstrip('\n').split('\t') for l in open(sys.argv[2], encoding='utf-8') if l.strip()]  # 242 이름·장수·묶음
    have = {r[0].replace('.json', ''): (int(r[1]), r[2].split()) for r in rows}
    bad = sorted({v for v in TO.values() if v not in names})
    assert not bad, f'붙일 이름이 우리 목록에 없다: {bad}'
    clash = sorted({v for v in NEW.values() if v in names})
    assert not clash, f'새 이름이 이미 있다: {clash}'
    missing = sorted(k for k in list(TO) + list(NEW) if k not in have)
    assert not missing, f'242 에 없는 이름: {missing}'
    target = collections.defaultdict(int); groups = collections.Counter()
    for src, dst in list(TO.items()) + list(NEW.items()):
        n, gs = have[src]; target[dst] += n
        for g in gs: groups[g] += 1
    print(f'242 이름 {len(TO) + len(NEW)}개 → 우리 이름 {len(target)}개(기존 {len(set(TO.values()))} + 새 {len(set(NEW.values()))})')
    print('쓸 장수(이름당 최대', PER_CLASS, '):', sum(min(v, PER_CLASS) for v in target.values()))
    print('필요한 묶음:', ' '.join(sorted(groups)))
    thin = {k: v for k, v in target.items() if v < 300}
    print('300장 미만인 이름:', thin)
