"""Generate the shared Kotlin registry from the reviewed guide dataset."""
import argparse
import hashlib
import json
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'research/exercise_guides/guides.ko.json'
TARGET = ROOT / 'app/src/main/java/com/example/trex_kotlin/ExerciseGuides.kt'
ASSETS = ROOT / 'app/src/main/assets'


def quote(value):
    return json.dumps(value, ensure_ascii=False).replace('$', '\\$')


def strings(values):
    return 'listOf(' + ', '.join(quote(value) for value in values) + ')'


def evidence_label(basis):
    if basis.startswith('related_'):
        return '유사 동작의 근전도 자료를 참고한 역할 해석'
    if basis.startswith(('direct_', 'exercise_EMG')):
        return '해당 동작의 근전도 참여 자료와 해부학적 역할 해석'
    if basis.startswith('professional_'):
        return '전문기관 동작 설명과 해부학적 역할 해석'
    return '해부학적 기능과 동작 구조에 근거한 추론'


def render(data):
    guides = data['guides']
    source_by_id = {s['id']: s for s in data['sources']}
    result = '''package com.example.trex_kotlin

// Generated by tools/generate_exercise_guides.py; edit research/exercise_guides/guides.ko.json.
// Educational roles are independent of the camera rollout and training-load weights.
internal data class GuideSource(val label: String, val url: String)
internal data class GuideMuscle(
    val name: String, val role: String, val function: String,
    val evidence: String, val sourceNumbers: List<Int>, val visibilityNote: String,
)
internal data class ExerciseGuide(
    val name: String, val asset: String, val comment: String,
    val setup: List<String>, val steps: List<String>, val breathing: String,
    val cautions: List<String>, val sourceName: String, val sourceUrl: String,
    val legend: String, val visualNote: String, val muscles: List<GuideMuscle>,
    val sources: List<GuideSource>,
)

internal object ExerciseGuides {
    const val breathingSource = "https://sportsmedicine.mayoclinic.org/news/weight-training-dos-and-donts-of-proper-technique/"
    val all: List<ExerciseGuide> by lazy { listOf(
'''
    result += ''.join(f"        {g['id']}(),\n" for g in guides)
    result += '''    ) }
    private val byName by lazy { all.associateBy { it.name } }
    fun forName(name: String): ExerciseGuide? = byName[name]
    fun introduction(name: String?, preparing: Boolean, seen: Set<String>): ExerciseGuide? =
        name?.takeIf { preparing && it !in seen }?.let(::forName)

'''
    for g in guides:
        sources = {}
        for ref in g['source_refs']:
            source = source_by_id[ref]
            sources[source['url']] = source['publisher'] + ' · 동작 안내'
        for m in g['muscle_roles']:
            for url in m['citations']:
                sources.setdefault(url, urlsplit(url).netloc.removeprefix('www.') + ' · 근육 근거')
        urls = list(sources)
        note = 'GIF는 주요 자세를 보여 주는 예시입니다. 동작 사이를 천천히 이어 주세요.'
        if g['id'] in ('plank', 'knee_plank', 'side_plank', 'knee_side_plank', 'single_leg_abdominal_press'):
            note = '자세 유지 운동입니다. GIF를 따라 몸을 위아래로 반복하지 말고 설명된 자세를 유지하세요.'
        if g['id'] == 'iyt_raise':
            note = 'I·Y·T 세 자세를 보여 줍니다. 각 자세에서 팔을 내린 뒤 다음 자세로 진행하세요.'
        note = g.get('image_variant_note', note)
        result += f"    private fun {g['id']}() = ExerciseGuide(\n"
        result += f"        {quote(g['name'])}, {quote(g['app_asset'])}, {quote(g['comment'])},\n"
        for field in ('setup', 'steps'):
            result += f"        {field} = {strings(g[field])},\n"
        result += f"        breathing = {quote(g['breathing'])},\n"
        result += f"        cautions = {strings(g['cautions'])},\n"
        result += f"        sourceName = {quote(sources[urls[0]])}, sourceUrl = {quote(urls[0])},\n"
        result += f"        legend = {quote(g['role_legend_ko'])}, visualNote = {quote(note)},\n"
        result += '        muscles = listOf(\n'
        for m in g['muscle_roles']:
            refs = ', '.join(str(urls.index(url) + 1) for url in m['citations'])
            visibility = {'deep': '깊은 근육', 'covered': '옷에 가려진 부위'}.get(m['visibility'], '')
            result += f"            GuideMuscle({quote(m['name_ko'])}, {quote(m['role'])}, {quote(m['function_ko'])}, {quote(evidence_label(m['evidence_basis']))}, listOf({refs}), {quote(visibility)}),\n"
        result += '        ),\n        sources = listOf(\n'
        result += ''.join(f'            GuideSource({quote(label)}, {quote(url)}),\n' for url, label in sources.items())
        result += '        ),\n    )\n\n'
    return result + '}\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = json.loads(SOURCE.read_text(encoding='utf-8'))
    guides = data['guides']
    assert len(guides) == len({g['name'] for g in guides}) == 72
    assert len({g['app_asset'] for g in guides}) == 72
    for g in guides:
        path = ASSETS / g['app_asset']
        assert hashlib.sha256(path.read_bytes()).hexdigest() == g['asset_sha256'], path
        assert g['setup'] and g['steps'] and g['breathing'] and g['cautions']
        assert all(m['citations'] and m['role'] in ('main', 'assist', 'stabilize') for m in g['muscle_roles'])
    content = render(data)
    if args.check:
        assert TARGET.read_text(encoding='utf-8') == content, 'Guide registry needs regeneration'
    else:
        TARGET.write_text(content, encoding='utf-8', newline='\n')
    print('72 guides and reviewed GIF hashes verified')


if __name__ == '__main__':
    main()
